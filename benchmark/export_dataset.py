"""Export a fixed, class-balanced subset of the committed test split to C.

The generated predictions are a correctness oracle, not training labels.
Regenerate after changing a model, then run the host parity test before flashing.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
import sys

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from dataset.generate import FEATURE_COLUMNS, LABELS  # noqa: E402
from training import train  # noqa: E402

DATA = ROOT / "dataset" / "data.csv"
OUT = ROOT / "firmware" / "main" / "benchmark_dataset.c"
COUNT_PER_CLASS = 64


def selected_rows():
    frame = pd.read_csv(DATA)
    test = frame.loc[frame.split == "test"]
    rng = np.random.default_rng(2026)
    groups = []
    for label in LABELS:
        part = test.loc[test.label == label]
        sequence_ids = part.seq_id.unique()
        chosen = sorted(rng.choice(sequence_ids, COUNT_PER_CLASS, replace=False))
        # One window per sequence avoids treating overlapping windows as
        # independent observations in this small hardware subset.
        groups.append(pd.DataFrame([
            part.loc[part.seq_id == seq_id].iloc[
                int(rng.integers((part.seq_id == seq_id).sum()))]
            for seq_id in chosen
        ]))
    assert all(len(group) == COUNT_PER_CLASS for group in groups)
    # Interleave classes so every short run contains all four classes.
    return pd.concat([pd.concat([g.iloc[[i]] for g in groups])
                      for i in range(COUNT_PER_CLASS)], ignore_index=True)


def render():
    rows = selected_rows()
    x = rows[FEATURE_COLUMNS].to_numpy(dtype=np.float32)
    labels = rows.label.map({name: i for i, name in enumerate(LABELS)}).to_numpy(dtype=np.uint8)
    splits = train.load_data()
    models = train.train_models(*splits["train"])
    predictions = {name: train.predict_ids(name, models[name], x).astype(np.uint8)
                   for name in train.METHODS}
    source_hash = hashlib.sha256(DATA.read_bytes()).hexdigest()
    subset_hash = hashlib.sha256(x.tobytes() + labels.tobytes()).hexdigest()
    lines = ["/* Generated by benchmark/export_dataset.py; do not edit. */",
             '#include "benchmark_dataset.h"',
             f'const char benchmark_dataset_sha256[] = "{source_hash}";',
             f'const char benchmark_subset_sha256[] = "{subset_hash}";',
             "const float benchmark_features[BENCHMARK_SAMPLES][NUM_FEATURES] = {"]
    for row in x:
        lines.append("    {" + ", ".join(f"{float(v):.9g}f" if "." in f"{float(v):.9g}" or "e" in f"{float(v):.9g}" else f"{float(v):.9g}.0f" for v in row) + "},")
    lines.append("};")
    for name, values in [("labels", labels), *predictions.items()]:
        symbol = "benchmark_labels" if name == "labels" else f"benchmark_expected_{name}"
        lines.append(f"const uint8_t {symbol}[BENCHMARK_SAMPLES] = {{")
        for i in range(0, len(values), 32):
            lines.append("    " + ", ".join(str(int(v)) for v in values[i:i+32]) + ",")
        lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    OUT.write_text(render())
    print(f"wrote {OUT} ({len(selected_rows())} test samples)")


if __name__ == "__main__":
    main()
