/* Shared interface for the four TinyEdgeBench inference methods.
   Hand-written; the predict_* implementations next to it are generated by
   training/export_models.py. */

#ifndef MODEL_API_H
#define MODEL_API_H

#include <stdint.h>

#define NUM_FEATURES 8
#define NUM_CLASSES 4

/* Feature order must match FEATURE_COLUMNS in dataset/generate.py. */
enum {
    F_TEMP = 0,
    F_HUM,
    F_LIGHT,
    F_D_TEMP,
    F_D_HUM,
    F_D_LIGHT,
    F_MOTION,
    F_DRIFT
};

/* Class order must match LABELS in dataset/generate.py. */
enum {
    CLASS_NORMAL = 0,
    CLASS_RAPID_CHANGE,
    CLASS_SLOW_DRIFT,
    CLASS_NOISY
};

extern const char *const class_names[NUM_CLASSES];

int predict_rule(const float *features);
int predict_logistic(const float *features);
int predict_tree(const float *features);
int predict_mlp(const float *features);

#endif /* MODEL_API_H */
