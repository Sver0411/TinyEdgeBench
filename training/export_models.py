"""Export the trained methods as plain C inference code.

Everything is float32, no quantisation, no external runtime. The generated
files live in firmware/main/models/ and are plain C, so they also compile on
the host for the Python/C parity test.

Run:
    python training/export_models.py
"""

from __future__ import annotations

from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dataset.generate import FEATURE_COLUMNS, LABELS  # noqa: E402
from training import rules, train  # noqa: E402

MODELS_DIR = ROOT / "firmware" / "main" / "models"

# Enum names used by firmware/main/models/model_api.h, in FEATURE_COLUMNS order.
FEATURE_ENUM = ("F_TEMP", "F_HUM", "F_LIGHT", "F_D_TEMP", "F_D_HUM", "F_D_LIGHT",
                "F_MOTION", "F_DRIFT")
CLASS_ENUM = ("CLASS_NORMAL", "CLASS_RAPID_CHANGE", "CLASS_SLOW_DRIFT", "CLASS_NOISY")

HEADER = "/* Generated by training/export_models.py - do not edit by hand. */\n"


def c_float(value):
    """Format a float as a C float literal."""
    text = f"{float(value):.9g}"
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def c_array(name, values, indent="    "):
    """Format a 1-D or 2-D sequence as a C array initialiser."""
    values = np.asarray(values)
    lines = [f"static const float {name}[] = {{" if values.ndim == 1
             else f"static const float {name}[{values.shape[0]}][{values.shape[1]}] = {{"]
    for row in (values if values.ndim == 2 else [values]):
        body = ", ".join(c_float(v) for v in row)
        # rows of a 2-D array need their own braces (-Wmissing-braces)
        lines.append(indent + ("{ " + body + " }," if values.ndim == 2 else body + ","))
    lines.append("};")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# rule
# --------------------------------------------------------------------------- #
def export_rule():
    code = f"""{HEADER}
#include "model_api.h"

/* Hand-written thresholds from training/rules.py, exported to C.
   Motion is normalised so 1.0 = "moves like sensor noise". */
#define MOTION_NOISY {c_float(rules.MOTION_NOISY)}
#define DRIFT_FAST {c_float(rules.DRIFT_FAST)}
#define DRIFT_ACTIVE {c_float(rules.DRIFT_ACTIVE)}
#define DIRECTED_RATIO {c_float(rules.DIRECTED_RATIO)}
#define NOISY_RATIO {c_float(rules.NOISY_RATIO)}

/* class_names[] lives in main.c so every build variant links it exactly once. */

int predict_rule(const float *features)
{{
    float motion = features[F_MOTION];
    float drift = features[F_DRIFT];
    float ratio = (motion > 1e-6f) ? (drift / motion) : 0.0f;

    if (motion >= MOTION_NOISY && ratio < NOISY_RATIO) {{
        return CLASS_NOISY;
    }}
    if (drift >= DRIFT_FAST && ratio >= DIRECTED_RATIO) {{
        return CLASS_RAPID_CHANGE;
    }}
    if (drift >= DRIFT_ACTIVE && ratio >= DIRECTED_RATIO) {{
        return CLASS_SLOW_DRIFT;
    }}
    if (motion >= MOTION_NOISY) {{
        return CLASS_NOISY;
    }}
    return CLASS_NORMAL;
}}
"""
    (MODELS_DIR / "model_rule.c").write_text(code)
    return MODELS_DIR / "model_rule.c"


# --------------------------------------------------------------------------- #
# logistic regression
# --------------------------------------------------------------------------- #
def export_logistic(model):
    scaler = model.named_steps["scaler"]
    clf = model.named_steps["clf"]
    inv_std = 1.0 / scaler.scale_

    code = f"""{HEADER}
#include "model_api.h"

/* StandardScaler: x = (x - mean) * inv_std */
{c_array("scaler_mean", scaler.mean_)}
{c_array("scaler_inv_std", inv_std)}

/* One row per class: weights[NUM_CLASSES][NUM_FEATURES] */
{c_array("weights", clf.coef_)}
{c_array("bias", clf.intercept_)}

int predict_logistic(const float *features)
{{
    float x[NUM_FEATURES];
    for (int i = 0; i < NUM_FEATURES; i++) {{
        x[i] = (features[i] - scaler_mean[i]) * scaler_inv_std[i];
    }}

    int best = 0;
    float best_score = bias[0];
    for (int i = 0; i < NUM_FEATURES; i++) {{
        best_score += weights[0][i] * x[i];
    }}

    for (int c = 1; c < NUM_CLASSES; c++) {{
        float score = bias[c];
        for (int i = 0; i < NUM_FEATURES; i++) {{
            score += weights[c][i] * x[i];
        }}
        if (score > best_score) {{
            best_score = score;
            best = c;
        }}
    }}
    return best;
}}
"""
    (MODELS_DIR / "model_logistic.c").write_text(code)
    return MODELS_DIR / "model_logistic.c"


# --------------------------------------------------------------------------- #
# decision tree
# --------------------------------------------------------------------------- #
def _tree_body(tree, node, depth, out):
    pad = "    " * (depth + 1)
    if tree.children_left[node] == -1:
        class_id = int(np.argmax(tree.value[node]))
        out.append(f"{pad}return {CLASS_ENUM[class_id]};")
        return
    feature = FEATURE_ENUM[int(tree.feature[node])]
    threshold = c_float(tree.threshold[node])
    out.append(f"{pad}if (features[{feature}] <= {threshold}) {{")
    _tree_body(tree, int(tree.children_left[node]), depth + 1, out)
    out.append(f"{pad}}} else {{")
    _tree_body(tree, int(tree.children_right[node]), depth + 1, out)
    out.append(f"{pad}}}")


def export_tree(model):
    out = []
    _tree_body(model.tree_, 0, 0, out)
    body = "\n".join(out)

    code = f"""{HEADER}
#include "model_api.h"

/* sklearn DecisionTreeClassifier(max_depth={train.TREE_MAX_DEPTH}) flattened
   into nested comparisons. No runtime tree structure on the device. */
int predict_tree(const float *features)
{{
{body}
}}
"""
    (MODELS_DIR / "model_tree.c").write_text(code)
    return MODELS_DIR / "model_tree.c"


# --------------------------------------------------------------------------- #
# tiny mlp
# --------------------------------------------------------------------------- #
def export_mlp(model):
    scaler = model.named_steps["scaler"]
    clf = model.named_steps["clf"]
    inv_std = 1.0 / scaler.scale_
    w1, w2, w3 = clf.coefs_
    b1, b2, b3 = clf.intercepts_
    h1, h2 = clf.hidden_layer_sizes

    code = f"""{HEADER}
#include "model_api.h"

/* StandardScaler: x = (x - mean) * inv_std */
{c_array("scaler_mean", scaler.mean_)}
{c_array("scaler_inv_std", inv_std)}

/* {len(FEATURE_COLUMNS)} -> {h1} -> {h2} -> {len(b3)}, ReLU on the hidden layers */
{c_array("w1", w1.T)}
{c_array("b1", b1)}
{c_array("w2", w2.T)}
{c_array("b2", b2)}
{c_array("w3", w3.T)}
{c_array("b3", b3)}

int predict_mlp(const float *features)
{{
    float x[NUM_FEATURES];
    for (int i = 0; i < NUM_FEATURES; i++) {{
        x[i] = (features[i] - scaler_mean[i]) * scaler_inv_std[i];
    }}

    float h1[{h1}];
    for (int j = 0; j < {h1}; j++) {{
        float sum = b1[j];
        for (int i = 0; i < NUM_FEATURES; i++) {{
            sum += w1[j][i] * x[i];
        }}
        h1[j] = sum > 0.0f ? sum : 0.0f;
    }}

    float h2[{h2}];
    for (int j = 0; j < {h2}; j++) {{
        float sum = b2[j];
        for (int i = 0; i < {h1}; i++) {{
            sum += w2[j][i] * h1[i];
        }}
        h2[j] = sum > 0.0f ? sum : 0.0f;
    }}

    int best = 0;
    float best_logit = b3[0];
    for (int i = 0; i < {h2}; i++) {{
        best_logit += w3[0][i] * h2[i];
    }}
    for (int c = 1; c < NUM_CLASSES; c++) {{
        float logit = b3[c];
        for (int i = 0; i < {h2}; i++) {{
            logit += w3[c][i] * h2[i];
        }}
        if (logit > best_logit) {{
            best_logit = logit;
            best = c;
        }}
    }}
    return best;
}}
"""
    (MODELS_DIR / "model_mlp.c").write_text(code)
    return MODELS_DIR / "model_mlp.c"


# --------------------------------------------------------------------------- #
# main
# --------------------------------------------------------------------------- #
def export_all(models=None):
    """Write all four C files. Returns the list of written paths."""
    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    if models is None:
        splits = train.load_data()
        models = train.train_models(*splits["train"])

    written = [export_rule(), export_logistic(models["logistic"]),
               export_tree(models["tree"]), export_mlp(models["mlp"])]
    return written


def main():
    splits = train.load_data()
    models = train.train_models(*splits["train"])
    for path in export_all(models):
        print(f"wrote {path}")
    for name in train.METHODS:
        size = train.estimate_size(name, models[name])
        raw = "N/A" if size["raw_constants_bytes"] is None else f"{size['raw_constants_bytes']} B"
        print(f"{name:10s} {raw:>7s}  ({size['raw_constants_note']})")


if __name__ == "__main__":
    main()
